      SUBROUTINE YMAXIMUM(ECM,Q_V,QT_V,YMAX)
      IMPLICIT NONE

      REAL*8 ECM,Q_V,QT_V,YMAX
      REAL*8 X,ACOSH,T1,T2,T3

      ACOSH(X)=DLOG(X+DSQRT(X**2-1.0))

      T1=ECM**2+Q_V**2
C      Print*, ' QT_V,Q_V ', QT_V,Q_V
      T2=DSQRT(QT_V**2+Q_V**2)
      T3=2.0*ECM*T2
C      Print*, ' ECM, X**2-1.0 ', ECM, (T1/T3)**2-1.0
      YMAX=ACOSH(T1/T3)

      RETURN
      END ! YMAXIMUM

